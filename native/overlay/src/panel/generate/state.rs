// What the external generate panel shows, and what the user can do in it. Mirrors the plugin's
// generate page (src/ui/app.ts): mode, prompt, favourites, references, count, the generate button,
// why it can't run, the workflow's bound parameters and the run's progress.
// The panel never works anything out itself: every value comes from the plugin (phase 3).

/// Thumbnail data is deliberately small; UXP sends a 128 px PNG/JPEG preview, never source bytes.
pub const MAX_REFERENCE_THUMB_URL_LEN: usize = 256_000;
pub const MAX_REFERENCE_THUMB_BYTES: usize = 192_000;
pub const MAX_REFERENCE_THUMB_EDGE: u32 = 512;
pub const MAX_REFERENCE_SLOTS: u32 = 8;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mode {
    Inpaint,
    Blend,
    Extract,
    Txt2img,
}

/// One mouse-wheel notch over the count field changes one variation, clamped to 1–4.
pub fn count_after_wheel(current: u32, delta_y: f32) -> u32 {
    if delta_y > 0.0 {
        current.saturating_add(1).clamp(1, 4)
    } else if delta_y < 0.0 {
        current.saturating_sub(1).clamp(1, 4)
    } else {
        current.clamp(1, 4)
    }
}

impl Mode {
    /// the tabs in the user's reference screenshot (扩图 / 放大 come later)
    pub const ALL: [Mode; 4] = [Mode::Inpaint, Mode::Blend, Mode::Extract, Mode::Txt2img];

    /// the plugin's TaskType
    pub fn key(self) -> &'static str {
        match self {
            Mode::Inpaint => "inpaint",
            Mode::Blend => "blend",
            Mode::Extract => "extract",
            Mode::Txt2img => "txt2img",
        }
    }

    pub fn from_key(key: &str) -> Option<Mode> {
        Mode::ALL.into_iter().find(|m| m.key() == key)
    }

    pub fn label(self) -> &'static str {
        match self {
            Mode::Inpaint => "局部重绘",
            Mode::Blend => "融图",
            Mode::Extract => "抠图",
            Mode::Txt2img => "文生图",
        }
    }
}

#[derive(Clone, Debug)]
pub enum Param {
    /// a bound number: slider + box, 复原 once it differs from the workflow's own value
    Number {
        key: String,
        label: String,
        value: f64,
        base: f64,
        min: f64,
        max: f64,
        int: bool,
    },
    Toggle {
        key: String,
        label: String,
        value: bool,
        tip: String,
    },
    /// 随机种子: every run random, or fixed to `value`
    Seed { random: bool, value: u64 },
}

#[derive(Clone)]
pub struct Reference {
    /// 参考 1 / 图2 … as the workflow names it
    pub tag: String,
    pub name: String,
    /// A small PNG/JPEG data URL generated by UXP; never the full source image.
    pub thumb: Option<String>,
    /// Decoded once and reused while the same slot/thumbnail remains active.
    pub texture: Option<eframe::egui::TextureHandle>,
    /// A failed decode is remembered so a malformed URL is not decoded on every frame.
    pub texture_error: Option<String>,
}

#[derive(Clone)]
pub struct RefSlot {
    pub slot: u32,
    pub filled: Option<Reference>,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum RefSource {
    Layer,
    File,
    Clipboard,
}

impl RefSource {
    pub const ALL: [RefSource; 3] = [RefSource::Layer, RefSource::File, RefSource::Clipboard];
    pub fn label(self) -> &'static str {
        match self {
            RefSource::Layer => "当前图层",
            RefSource::File => "图片文件",
            RefSource::Clipboard => "剪贴板",
        }
    }
}

#[derive(Clone, Debug)]
pub struct Run {
    pub stage: String,
    pub progress: f32,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[allow(dead_code)] // Error arrives with the plugin's messages (phase 3)
pub enum Tone {
    Info,
    Ok,
    Error,
}

#[derive(Clone)]
pub struct PanelState {
    /// the tab that is lit; the plugin only ever sends one of the four (None before its first state)
    pub mode: Option<Mode>,
    pub prompt: String,
    /// the grey line under the prompt (the mode's / workflow's hint)
    pub hint: String,
    pub favorites: Vec<String>,
    pub refs: Vec<RefSlot>,
    pub count: u32,
    /// 生成 / 融图 / 抠图 / 生成更多变体 …
    pub action: String,
    /// why 生成 can't run now; None = it can
    pub blocked: Option<String>,
    pub params: Vec<Param>,
    pub running: Option<Run>,
    pub status: Option<(Tone, String)>,
    /// a line under the button about what 开始 will do (the plugin panel is in 放大 / 扩图 …)
    pub note: Option<String>,
    /// 「AI 优化」 (DeepSeek) beside 收藏; None: the mode has no prompt to optimise
    pub ai: Option<AiPrompt>,
    // ── panel-local, never sent back ──
    pub fav_open: bool,
    pub adv_open: bool,
    /// the slot whose 当前图层 / 图片文件 / 剪贴板 choice is open
    pub ref_menu: Option<u32>,
    /// the count box's text while it's being typed in
    pub count_text: String,
    /// the prompt / count box has the keyboard: the plugin's copy doesn't overwrite it
    pub prompt_focused: bool,
    pub count_focused: bool,
    /// A normal layer being dragged from WaveLayer toward one of the reference slots.
    pub external_drag: Option<super::super::ExternalLayerDrag>,
}

/// The plugin's 「AI 优化」 state: running, why it can't run (None: it can), 还原 offered.
#[derive(Clone, Debug, Default, PartialEq, serde::Deserialize)]
pub struct AiPrompt {
    #[serde(default)]
    pub busy: bool,
    #[serde(default)]
    pub blocked: Option<String>,
    #[serde(default)]
    pub undo: bool,
}

/// What the user did. Phase 3 sends these to the plugin, which runs its own handlers.
#[derive(Clone, Debug, PartialEq)]
pub enum Action {
    SetMode(Mode),
    SetPrompt(String),
    ToggleFavorite,
    /// 「AI 优化」 / 还原 (the plugin asks DeepSeek and puts the result in the prompt)
    OptimizePrompt,
    RestorePrompt,
    PickFavorite(String),
    RemoveFavorite(String),
    AddRef { slot: u32, source: RefSource },
    RemoveRef(u32),
    DropRefs {
        slot: u32,
        doc_id: u32,
        layers: Vec<super::super::DraggedLayer>,
        total_count: usize,
    },
    SetCount(u32),
    SetNumber { key: String, value: f64 },
    ResetNumber(String),
    SetToggle { key: String, value: bool },
    SetSeed { random: bool, value: u64 },
    NewSeed,
    /// carries the mode its tab showed when 开始 was clicked: the plugin runs that one
    Generate(Option<Mode>),
    Cancel,
}

#[cfg(test)]
mod tests {
    use super::count_after_wheel;

    #[test]
    fn count_wheel_steps_are_bounded_to_one_through_four() {
        assert_eq!(count_after_wheel(2, 1.0), 3);
        assert_eq!(count_after_wheel(2, -1.0), 1);
        assert_eq!(count_after_wheel(1, -1.0), 1);
        assert_eq!(count_after_wheel(4, 1.0), 4);
        assert_eq!(count_after_wheel(0, 0.0), 1);
        assert_eq!(count_after_wheel(9, 0.0), 4);
    }
}
